        /// <summary>Resolve the executable path of a process id, or null when it cannot be read.</summary>
        public static string ProcessImagePath(uint pid)
        {
            IntPtr h = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid);
            if (h == IntPtr.Zero) return null;
            try
            {
                uint size = 1024;
                var sb = new StringBuilder((int)size);
                if (!QueryFullProcessImageNameW(h, 0, sb, ref size)) return null;
                return sb.ToString(0, (int)size);
            }
            finally { CloseHandle(h); }
        }

        /// <summary>Resolve a process id to its session, or uint.MaxValue when unknown.</summary>
        public static uint ProcessSession(uint pid)
        {
            uint s;
            return ProcessIdToSessionId(pid, out s) ? s : uint.MaxValue;
        }
